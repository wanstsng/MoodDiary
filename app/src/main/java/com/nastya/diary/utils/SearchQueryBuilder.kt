package com.nastya.diary.utils

/**
 * Подготовка пользовательского ввода к полнотекстовому поиску.
 *
 * Строку из поля поиска нельзя передавать в `MATCH` как есть: у FTS свой
 * язык запросов, где кавычки, скобки, дефис и слова `AND`, `OR`, `NEAR`
 * имеют особый смысл. Ввод вроде `код -ошибки` или незакрытая кавычка
 * привели бы к синтаксической ошибке SQL — то есть к падению поиска на
 * совершенно обычном для пользователя тексте.
 */
object SearchQueryBuilder {

    /** Всё, что не буква и не цифра, считается разделителем слов. */
    private val WORD_PATTERN = Regex("""[\p{L}\p{N}]+""")

    /**
     * Превращает пользовательский ввод в безопасный запрос FTS.
     *
     * Из строки берутся только слова, к каждому добавляется `*` — поиск
     * идёт по началу слова, поэтому «парк» находит и «парке», и «Парковка».
     * Слова соединяются пробелом, что в FTS означает «И»: чем больше слов
     * ввёл пользователь, тем точнее результат.
     *
     * @return запрос для `MATCH` или пустая строка, если искать нечего
     */
    fun build(rawQuery: String): String = WORD_PATTERN
        .findAll(rawQuery)
        .joinToString(separator = " ") { match -> "${match.value}*" }

    /**
     * Слова запроса без служебных символов — для подсветки совпадений
     * в списке записей.
     */
    fun words(rawQuery: String): List<String> = WORD_PATTERN
        .findAll(rawQuery)
        .map { it.value }
        .toList()
}
